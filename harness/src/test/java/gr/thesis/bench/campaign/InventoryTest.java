package gr.thesis.bench.campaign;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** The inventory is Terraform's OUTPUT (main.tf local_file.inventory) —
 *  this fixture is byte-shaped like what that template emits. */
class InventoryTest {

    private static final String FIXTURE = """
            # GENERATED by terraform apply — do not edit by hand.
            # Public IPs: laptop -> VM (SSH admin). Private IPs: inter-node only.
            PUBLIC_NODE1=203.0.113.11
            PUBLIC_NODE2=203.0.113.12
            PUBLIC_NODE3=203.0.113.13
            PUBLIC_LOADGEN=203.0.113.20
            PUBLIC_OBS=203.0.113.21

            PRIVATE_NODE1=10.0.0.11
            PRIVATE_NODE2=10.0.0.12
            PRIVATE_NODE3=10.0.0.13
            PRIVATE_LOADGEN=10.0.0.20
            PRIVATE_OBS=10.0.0.21

            CONSENSUS_NODE_COUNT=3
            CONSENSUS_NODE_TYPE=ccx13
            SSH_KEY=/root/.ssh/hetzner_thesis
            LOCATION=fsn1
            """;

    @Test
    void parsesNodeOrderLoadgenAndKey(@TempDir Path dir) throws Exception {
        Path f = dir.resolve("inventory.env");
        Files.writeString(f, FIXTURE);
        Inventory inv = Inventory.parse(f);
        assertEquals(List.of("10.0.0.11", "10.0.0.12", "10.0.0.13"), inv.nodePrivateIps(),
                "node order = index identity — everything downstream depends on it");
        assertEquals("10.0.0.20", inv.loadgenPrivateIp());
        assertEquals(Path.of("/root/.ssh/hetzner_thesis"), inv.sshKey());
    }

    @Test
    void tildeInSshKeyExpandsToUserHome(@TempDir Path dir) throws Exception {
        Path f = dir.resolve("inventory.env");
        Files.writeString(f, FIXTURE.replace("/root/.ssh/hetzner_thesis", "~/.ssh/k"));
        assertTrue(Inventory.parse(f).sshKey().startsWith(System.getProperty("user.home")),
                "~ must expand — sshj cannot open a literal tilde path");
    }

    @Test
    void missingNodeEntryFailsClosedNamingKeyAndFile(@TempDir Path dir) throws Exception {
        Path f = dir.resolve("inventory.env");
        Files.writeString(f, FIXTURE.replace("PRIVATE_NODE2=10.0.0.12\n", ""));
        var e = assertThrows(IllegalArgumentException.class, () -> Inventory.parse(f));
        assertTrue(e.getMessage().contains("PRIVATE_NODE2"), e.getMessage());
        assertTrue(e.getMessage().contains("inventory.env"), e.getMessage());
    }

    @Test
    void theObsVmIsOptionalBecauseTheCanaryHasNone(@TempDir Path dir) throws Exception {
        // Terraform emits PRIVATE_OBS for a full phase, but P3.4's canary is
        // two VMs with no obs stack. Absent must mean "no metrics export",
        // which the ValidityChecker already surfaces as a loud SKIP — not a
        // parse failure over infrastructure the run was never given.
        Path f = dir.resolve("inv.env");
        Files.writeString(f, """
                CONSENSUS_NODE_COUNT=1
                PRIVATE_NODE1=10.0.0.11
                PRIVATE_LOADGEN=10.0.0.20
                SSH_KEY=/tmp/k
                """);
        assertTrue(Inventory.parse(f).obsPrivateIp().isEmpty());

        Path g = dir.resolve("inv2.env");
        Files.writeString(g, """
                CONSENSUS_NODE_COUNT=1
                PRIVATE_NODE1=10.0.0.11
                PRIVATE_LOADGEN=10.0.0.20
                PRIVATE_OBS=10.0.0.21
                SSH_KEY=/tmp/k
                """);
        assertEquals("10.0.0.21", Inventory.parse(g).obsPrivateIp().orElseThrow());
    }
}
